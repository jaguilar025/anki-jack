// Clave para almacenar categorías personalizadas en localStorage
const CUSTOM_CATEGORIES_KEY = "nihongo-study-custom-categories";

// Guardar categorías personalizadas en localStorage
export function saveCustomCategories(customCategories: Category): void {
  if (typeof window === "undefined") return;

  localStorage.setItem(CUSTOM_CATEGORIES_KEY, JSON.stringify(customCategories));
}

// Obtener categorías personalizadas de localStorage
export function getCustomCategories(): Category | null {
  if (typeof window === "undefined") return null;

  const stored = localStorage.getItem(CUSTOM_CATEGORIES_KEY);
  if (!stored) return null;

  try {
    return JSON.parse(stored) as Category;
  } catch (error) {
    console.error("Error parsing custom categories:", error);
    return null;
  }
}

// Eliminar categorías personalizadas de localStorage
export function clearCustomCategories(): void {
  if (typeof window === "undefined") return;

  localStorage.removeItem(CUSTOM_CATEGORIES_KEY);
}

// Obtener todas las categorías (predefinidas + personalizadas)
export function getAllCategories(): Category {
  const customCategories = getCustomCategories();
  if (customCategories) {
    return { ...categories, ...customCategories };
  }
  return categories;
}
